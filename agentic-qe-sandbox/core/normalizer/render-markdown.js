/**
 * Renders a UnifiedRequirement[] (see normalize.js) as the unified
 * requirements markdown doc. Like normalize.js, this has no format-specific
 * knowledge — it only knows the unified shape.
 */

function gherkinBlock(req) {
  const lines = [];
  req.given.forEach((g, i) => lines.push(`    ${i === 0 ? "Given" : "And"} ${g}`));
  req.when.forEach((w, i) => lines.push(`    ${i === 0 ? "When" : "And"} ${w}`));
  req.then.forEach((t, i) => lines.push(`    ${i === 0 ? "Then" : "And"} ${t}`));
  return lines.join("\n");
}

function traceabilityLine(req) {
  const { app, format, file, line, specId } = req.source;
  const loc = line ? `${file}:${line}` : file;
  const spec = specId ? ` (\`${specId}\`)` : "";
  return `_Source: ${app} / ${format} — \`${loc}\`${spec}_`;
}

/**
 * @param {Array<ReturnType<typeof import('./normalize.js').normalize>[number]>} unified
 */
export function renderMarkdown(unified) {
  const byApp = new Map();
  for (const req of unified) {
    if (!byApp.has(req.source.app)) byApp.set(req.source.app, new Map());
    const byFeature = byApp.get(req.source.app);
    if (!byFeature.has(req.feature)) byFeature.set(req.feature, []);
    byFeature.get(req.feature).push(req);
  }

  const out = [];
  out.push("# Unified Requirements");
  out.push("");
  out.push(
    "Generated by `core/normalizer` from per-adapter `RawRequirementItem[]` extracts. " +
      "Every acceptance criterion below carries a traceability pointer back to its source artifact."
  );
  out.push("");
  out.push(`Total requirements: ${unified.length} across ${byApp.size} app(s).`);
  out.push("");

  for (const [app, byFeature] of byApp) {
    out.push(`## Source: ${app}`);
    out.push("");
    for (const [feature, reqs] of byFeature) {
      out.push(`### Feature: ${feature}`);
      out.push("");
      for (const req of reqs) {
        out.push(`#### \`${req.id}\` — ${req.title}`);
        out.push("");
        out.push(`> ${req.userStory}`);
        out.push("");
        out.push("```gherkin");
        out.push(gherkinBlock(req));
        out.push("```");
        out.push("");
        out.push(traceabilityLine(req));
        out.push("");
      }
    }
  }

  return out.join("\n");
}

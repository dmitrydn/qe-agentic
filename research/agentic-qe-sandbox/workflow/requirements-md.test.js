import { test } from "node:test";
import assert from "node:assert/strict";
import { parseUnifiedRequirementsMarkdown, toRequirement } from "./requirements-md.js";

const SAMPLE = `# Unified Requirements

Generated by core/normalizer.

## Source: app-a

### Feature: Widgets

#### \`APP-A-WIDGETS-001\` — creates a widget

> As a user of app-a, I want "creates a widget" so that the Widgets feature behaves as specified.

\`\`\`gherkin
    Given the database has been seeded
    And the requesting client is authenticated
    When a POST /widgets request is made
    And creates a widget
    Then the response status is 201
\`\`\`

_Source: app-a / fmt-x — \`some/file.ts:42\` (\`POST /widgets\`)_

## Source: app-b

### Feature: Things

#### \`APP-B-THINGS-001\` — lists things

> As a user of app-b, I want "lists things" so that the Things feature behaves as specified.

\`\`\`gherkin
    Given the database has been seeded
    When a GET /things request is made
    Then the response status is 200
\`\`\`

_Source: app-b / fmt-y — \`other/file.ts:7\` (\`GET /things\`)_
`;

test("parseUnifiedRequirementsMarkdown extracts records across multiple apps", () => {
  const records = parseUnifiedRequirementsMarkdown(SAMPLE);
  assert.equal(records.length, 2);
  assert.equal(records[0].app, "app-a");
  assert.equal(records[0].id, "APP-A-WIDGETS-001");
  assert.equal(records[0].title, "creates a widget");
  assert.deepEqual(records[0].given, ["the database has been seeded", "the requesting client is authenticated"]);
  assert.deepEqual(records[0].when, ["a POST /widgets request is made", "creates a widget"]);
  assert.deepEqual(records[0].then, ["the response status is 201"]);
  assert.equal(records[0].source.file, "some/file.ts");
  assert.equal(records[0].source.line, 42);
  assert.equal(records[0].source.specId, "POST /widgets");

  assert.equal(records[1].app, "app-b");
  assert.equal(records[1].id, "APP-B-THINGS-001");
});

test("toRequirement maps a record to the Requirement schema shape, inferring apiHints from specId", () => {
  const records = parseUnifiedRequirementsMarkdown(SAMPLE);
  const req = toRequirement(records[0]);
  assert.equal(req.id, "APP-A-WIDGETS-001");
  assert.equal(req.title, "creates a widget");
  assert.ok(req.acceptanceCriteria.includes("When a POST /widgets request is made"));
  assert.deepEqual(req.source, { file: "some/file.ts", ref: "42" });
  assert.deepEqual(req.apiHints, [{ method: "POST", path: "/widgets" }]);
});

test("toRequirement prefers curated extraApiHints over inferred ones", () => {
  const records = parseUnifiedRequirementsMarkdown(SAMPLE);
  const curated = [{ method: "POST", path: "/widgets", auth: "primaryUser", notes: "curated" }];
  const req = toRequirement(records[0], curated);
  assert.deepEqual(req.apiHints, curated);
});

test("toRequirement omits apiHints when specId doesn't look like 'METHOD /path'", () => {
  const md = SAMPLE.replace("(`POST /widgets`)", "(`some free-form spec id`)");
  const records = parseUnifiedRequirementsMarkdown(md);
  const req = toRequirement(records[0]);
  assert.equal(req.apiHints, undefined);
});
